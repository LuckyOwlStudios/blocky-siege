package net.luckystudios.datagen.types;

import net.luckystudios.BlockySiege;
import net.luckystudios.init.ModBlocks;
import net.luckystudios.init.ModItems;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.data.PackOutput;
import net.minecraft.world.item.Item;
import net.neoforged.neoforge.client.model.generators.ItemModelBuilder;
import net.neoforged.neoforge.client.model.generators.ItemModelProvider;
import net.neoforged.neoforge.common.data.ExistingFileHelper;

public class ModItemModelProvider extends ItemModelProvider {
    public ModItemModelProvider(PackOutput output, ExistingFileHelper existingFileHelper) {
        super(output, BlockySiege.MOD_ID, existingFileHelper);
    }

    /** Vanilla trim_type values for each trim material, so the item icon can show the trim like armor does. */
    private static final String[] TRIM_MATERIALS = {"quartz", "iron", "netherite", "redstone", "copper", "gold", "emerald", "diamond", "lapis", "amethyst"};

    /**
     * A flat item icon that gains a trim overlay (the paletted sprite blockysiege:trims/<overlay>_<material>,
     * generated by assets/minecraft/atlases/blocks.json) when the stack carries a trim.
     */
    private void trimmableItem(Item item, String overlay) {
        String name = BuiltInRegistries.ITEM.getKey(item).getPath();
        ItemModelBuilder base = this.basicItem(item);
        for (int i = 0; i < TRIM_MATERIALS.length; i++) {
            String trimModelName = name + "_" + TRIM_MATERIALS[i] + "_trim";
            this.withExistingParent(trimModelName, mcLoc("item/generated"))
                    .texture("layer0", modLoc("item/" + name))
                    .texture("layer1", modLoc("trims/" + overlay + "_" + TRIM_MATERIALS[i]));
            base.override().predicate(mcLoc("trim_type"), (i + 1) / 10.0F).model(this.getExistingFile(modLoc("item/" + trimModelName))).end();
        }
    }

    @Override
    protected void registerModels() {
        this.basicItem(ModItems.WOODEN_SHRAPNEL.get());
        this.basicItem(ModItems.FORT_BANNER_PATTERN.get());
        this.withExistingParent(ModItems.CROSSBOW_GOLEM_SPAWN_EGG.getId().getPath(), mcLoc("item/template_spawn_egg"));

        // Blocks whose in-world model is hand-authored but whose item is a flat 2D icon
        this.trimmableItem(ModBlocks.CANNON.get().asItem(), "cannon_trim");
        this.trimmableItem(ModBlocks.MULTI_CANNON.get().asItem(), "burst_cannon_trim");
        this.trimmableItem(ModBlocks.SPEWER_CANNON.get().asItem(), "spewer_trim");
        this.basicItem(ModBlocks.VOLLEY_RACK.get().asItem());
        this.basicItem(ModBlocks.CROSSBOW_GOLEM_BLOCK.get().asItem());
    }
}
